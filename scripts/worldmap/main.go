// Command worldmap writes internal/worldmap/shapes.go from Natural Earth's
// 1:110m admin-0 countries, as GeoJSON:
//
//	curl -L -o ne_110m.geojson https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_admin_0_countries.geojson
//	go run ./scripts/worldmap ne_110m.geojson > internal/worldmap/shapes.go
//
// Each country is one SVG path in worldmap.Project's units, to the whole
// unit (a unit is under a pixel at the size the map is drawn), keyed by its ISO 3166 code (ISO_A2_EH, which names France and Norway
// where ISO_A2 does not). Antarctica is left out; a territory with no code
// is drawn as land with none.
package main

import (
	"encoding/json"
	"fmt"
	"os"
	"sort"
	"strconv"
	"strings"

	"github.com/johalputt/vayupress/internal/worldmap"
)

type feature struct {
	Properties struct {
		Code string `json:"ISO_A2_EH"`
		Name string `json:"NAME"`
	} `json:"properties"`
	Geometry struct {
		Type        string          `json:"type"`
		Coordinates json.RawMessage `json:"coordinates"`
	} `json:"geometry"`
}

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: worldmap countries.geojson > internal/worldmap/shapes.go")
		os.Exit(2)
	}
	raw, err := os.ReadFile(os.Args[1])
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	var fc struct{ Features []feature }
	if err := json.Unmarshal(raw, &fc); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	type shape struct{ code, name, d string }
	var out []shape
	for _, f := range fc.Features {
		if f.Properties.Name == "Antarctica" {
			continue
		}
		var polys [][][][2]float64
		switch f.Geometry.Type {
		case "Polygon":
			var p [][][2]float64
			if err := json.Unmarshal(f.Geometry.Coordinates, &p); err != nil {
				panic(err)
			}
			polys = [][][][2]float64{p}
		case "MultiPolygon":
			if err := json.Unmarshal(f.Geometry.Coordinates, &polys); err != nil {
				panic(err)
			}
		default:
			continue
		}
		var d strings.Builder
		for _, poly := range polys {
			for _, ring := range poly {
				last := ""
				for i, c := range ring {
					x, y := worldmap.Project(c[1], c[0])
					p := num(x) + "," + num(y)
					if p == last {
						continue
					}
					if i == 0 {
						d.WriteString("M" + p)
					} else {
						d.WriteString("L" + p)
					}
					last = p
				}
				d.WriteString("Z")
			}
		}
		code := f.Properties.Code
		if code == "-99" {
			code = ""
		}
		out = append(out, shape{code, f.Properties.Name, d.String()})
	}
	sort.Slice(out, func(i, j int) bool { return out[i].name < out[j].name })
	fmt.Println("// Code generated by scripts/worldmap from Natural Earth's 1:110m admin-0 countries (public domain); DO NOT EDIT.")
	fmt.Println()
	fmt.Println("package worldmap")
	fmt.Println()
	fmt.Println("// Shapes are the countries, each its ISO 3166 code (\"\" for a territory")
	fmt.Println("// with none), its name and its outline as an SVG path in Project's units.")
	fmt.Println("var Shapes = []Shape{")
	for _, s := range out {
		fmt.Printf("\t{%q, %q, %q},\n", s.code, s.name, s.d)
	}
	fmt.Println("}")
}

func num(v float64) string { return strconv.Itoa(int(v + 0.5)) }
